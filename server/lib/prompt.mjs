// 每条资料最多列出的图片数(个别小节图片很多, 全量列出会撑爆上下文)
const MAX_IMAGES_PER_SOURCE = 6

export function buildSystemPrompt(sources) {
  const parts = [RULES, SITE_BRIEF]
  if (sources.length) {
    const ctx = sources
      .map((s, i) => {
        let block = `[${i + 1}] 《${s.chunk.page}》› ${s.chunk.heading}\n${s.chunk.text}`
        const imgs = s.chunk.images ?? []
        if (imgs.length) {
          const shown = imgs.slice(0, MAX_IMAGES_PER_SOURCE)
          block +=
            '\n' +
            shown
              .map((im, j) => `[图${j + 1}] ${im.url}${im.alt ? `（${im.alt}）` : ''}`)
              .join('\n')
          if (imgs.length > shown.length) block += `\n（本节另有 ${imgs.length - shown.length} 张图, 未列出）`
        }
        return block
      })
      .join('\n\n')
    parts.push(`【参考资料】(与用户问题最相关的文档片段)\n${ctx}`)
  } else {
    parts.push('【参考资料】(无——知识库中未检索到与本次问题相关的内容, 请按规范第 3 条回答)')
  }
  return parts.join('\n\n')
}
